document.querySelectorAll(".carousel").forEach(track => {
  const wrap = document.createElement("div");
  wrap.className = "carousel-wrap";
  track.parentNode.insertBefore(wrap, track);
  wrap.appendChild(track);
  const mk = (dir, label) => {
    const b = document.createElement("button");
    b.type = "button";
    b.className = "car-btn " + (dir < 0 ? "prev" : "next");
    b.setAttribute("aria-label", dir < 0 ? "Previous" : "Next");
    b.textContent = label;
    b.addEventListener("click", () => track.scrollBy({ left: dir * track.clientWidth * 0.8, behavior: "smooth" }));
    wrap.appendChild(b);
    return b;
  };
  const prev = mk(-1, "‹"), next = mk(1, "›");
  const update = () => {
    prev.hidden = track.scrollLeft < 8;
    next.hidden = track.scrollLeft + track.clientWidth >= track.scrollWidth - 8;
  };
  track.addEventListener("scroll", update, { passive: true });
  window.addEventListener("resize", update);
  new MutationObserver(update).observe(track, { childList: true });
  update();
});
